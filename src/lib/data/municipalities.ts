/** 市区町村名であいまい検索 */
export function searchMunicipalities(query: string): MunicipalityResult[] {
  if (!query.trim()) return [];
  const q = query.trim().replace(/\s+/g, '');
  return MUNICIPALITIES.filter(
    (m) =>
      m.name.includes(q) ||
      `${m.prefName}${m.name}`.includes(q) ||
      m.code.startsWith(q)
  ).slice(0, 10);
}

/** コードから市区町村を取得 */
export function getMunicipalityByCode(code: string): MunicipalityResult | undefined {
  return MUNICIPALITIES.find((m) => m.code === code);
}
